"""FPL server time for the forecast record (M1.5; ``season-evaluation.md`` §2.3).

The host's clocks — the Colima VM's and the database's — can lag after the laptop sleeps, so
they cannot show that a forecast existed before a deadline; nor can the absence of FPL news
stamped after it (that is a leakage check, not a clock). FPL's own API can: every response
carries an HTTP ``Date`` header from FPL's CDN. A response cannot be generated before its
request was sent, nor received before it was generated, so:

* a request sent **after** the forecast file was written and hashed gives
  ``not_after = Date + Age + 1 s`` — the file existed by then. ``Age`` (seconds the body sat in
  a cache) keeps it an upper bound whether the CDN sets ``Date`` at delivery (Fastly does:
  observed equal to an NTP-synced clock within a second while ``Age`` was 276 s) or keeps the
  origin's; the second covers ``Date``'s whole-second resolution;
* a response received **before** the computation started gives ``not_before = Date``.

Only ``https://fantasy.premierleague.com`` counts: the request goes through the ingestion
client's allowlist with redirects disabled, and every stored source URL is checked again when a
checkpoint is judged. The host's own clock at send and receipt is stored beside it as a skew
measurement, never as evidence. Reaching FPL can fail; a failure is logged and leaves the
forecast without attestation (at best ``prospective_unverified``) — it never blocks serving.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from email.utils import parsedate_to_datetime
from typing import Any, Protocol
from urllib.parse import urlparse

import structlog

from fpl_ingestion.http import HttpConfig, HttpFetcher

log = structlog.get_logger("fpl_api.attestation")
OFFICIAL_HOST = "fantasy.premierleague.com"
PATH = "event-status/"  # a small response that every FPL client polls


class UntrustedTimeSource(ValueError):
    """A time from anywhere but FPL's official API over HTTPS."""


def official(url: str) -> bool:
    u = urlparse(url)
    return u.scheme == "https" and u.hostname == OFFICIAL_HOST


@dataclass(frozen=True)
class ServerTime:
    url: str
    date: datetime  # the response's Date header
    age_seconds: int  # its Age header (0 when absent)
    local_sent: datetime  # this host's clock: skew measurement only
    local_received: datetime
    served_by: str | None = None

    @property
    def not_before(self) -> datetime:
        """The response was generated by then, so anything started after receipt started
        after this."""
        return self.date

    @property
    def not_after(self) -> datetime:
        """The request was sent by then, so anything finished before sending finished by
        this."""
        return self.date + timedelta(seconds=self.age_seconds + 1)

    def evidence(self) -> dict[str, Any]:
        return {
            "url": self.url,
            "date": self.date.isoformat(),
            "age_seconds": self.age_seconds,
            "served_by": self.served_by,
            "local_sent": self.local_sent.isoformat(),
            "local_received": self.local_received.isoformat(),
            # host clock minus FPL's at receipt (positive: the host runs ahead)
            "host_skew_seconds": round((self.local_received - self.date).total_seconds(), 3),
        }


def from_response(
    url: str, headers: Any, local_sent: datetime, local_received: datetime
) -> ServerTime:
    """Parse a response's ``Date`` and ``Age``; raises unless both are well-formed and the URL
    is FPL's official API."""
    if not official(url):
        raise UntrustedTimeSource(f"{url} is not {OFFICIAL_HOST} over https")
    raw = headers.get("date")
    if not raw:
        raise ValueError(f"{url}: no Date header")
    date = parsedate_to_datetime(raw)
    if date.tzinfo is None:
        raise ValueError(f"{url}: Date {raw!r} has no zone")
    age_raw = str(headers.get("age", "0")).split(",")[0].strip()
    if not age_raw.isdigit():
        raise ValueError(f"{url}: Age {age_raw!r} is not a number of seconds")
    return ServerTime(
        url=url,
        date=date.astimezone(UTC),
        age_seconds=int(age_raw),
        local_sent=local_sent,
        local_received=local_received,
        served_by=headers.get("x-served-by"),
    )


class ServerClock(Protocol):
    def now(self) -> ServerTime: ...


class FplServerClock:
    """FPL's server time through the ingestion client (allowlist, https only, no redirects).
    Two attempts and a short timeout: a forecast job waits at most about half a minute."""

    def __init__(self, fetcher: HttpFetcher, base_url: str) -> None:
        self.fetcher = fetcher
        self.url = f"{base_url.rstrip('/')}/{PATH}"
        if not official(self.url):
            raise UntrustedTimeSource(f"{self.url} is not {OFFICIAL_HOST} over https")

    @classmethod
    def from_config(cls, cfg: dict[str, Any]) -> FplServerClock:
        api = cfg["fpl_api"]
        fetcher = HttpFetcher(
            HttpConfig(
                allowed_hosts=tuple(api["allowed_hosts"]),
                timeout_seconds=10.0,
                max_retries=2,
                backoff_initial_seconds=1.0,
                backoff_max_seconds=4.0,
                user_agent=str(api["user_agent"]),
            )
        )
        return cls(fetcher, str(api["base_url"]))

    def now(self) -> ServerTime:
        sent = datetime.now(UTC)
        res = self.fetcher.get(self.url)
        return from_response(res.url, res.headers, sent, datetime.now(UTC))


def read(clock: ServerClock | None, purpose: str) -> ServerTime | None:
    """FPL's time, or None (logged) without a clock or when FPL cannot be reached."""
    if clock is None:
        return None
    try:
        return clock.now()
    except Exception as exc:  # an outage, a refused host, a malformed header: no evidence
        log.warning("server_time_unavailable", purpose=purpose, error=str(exc)[:300])
        return None
