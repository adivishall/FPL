"""Past-season reference for the Season Review (M1.5; ``season-evaluation.md`` §7).

Re-summarises the stored 2023-26 walk-forward rows (``data/eval/forecast_eval_rows.parquet``,
produced by ``forecast_eval.py``; horizon 0) with the live record's per-gameweek statistics
(``fpl_forecasting.season_eval``), so the page can show the past seasons over the same gameweeks
as the live record by the same method. No refit and no new information access.

Two estimators differ from the live record's, as published: the randomised PIT (central-80
coverage as an indicator per row) and the CRPS with self-pairs (its bias is under 1 % of the
past-season CRPS margin). The per-gameweek SDs printed at the end are those the contract's
calibration margins were checked against.

Usage: uv run python ml/experiments/season_reference.py
Outputs: ml/reports/season_reference.{json,md}
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from fpl_forecasting import season_eval as se

ROOT = Path(__file__).resolve().parents[2]


def standardise(rows: pd.DataFrame) -> pd.DataFrame:
    """The stored rows in ``season_eval.ROW_INPUTS`` terms."""
    pit = rows["pit_mc"].to_numpy(float)
    return rows.assign(
        y=rows["points"].astype(float),
        minutes_actual=rows["act_minutes"].astype(float),
        starts_actual=rows["act_starts"].astype(float),
        start_probability=rows["prob_start"].astype(float),
        crps_model=rows["crps_mc"].astype(float),
        pit80=((pit >= 0.1) & (pit <= 0.9)).astype(float),
        pit_lo=(pit < 0.1).astype(float),
        pit_hi=(pit > 0.9).astype(float),
    )


def main() -> None:
    raw = pd.read_parquet(ROOT / "data" / "eval" / "forecast_eval_rows.parquet")
    rows = standardise(raw[raw["horizon"] == 0].reset_index(drop=True))
    out: dict[str, Any] = {
        "generated": datetime.now(UTC).isoformat(timespec="seconds"),
        "source": "data/eval/forecast_eval_rows.parquet (walk-forward 2023-26, horizon 0)",
        "evaluator_version": se.EVALUATOR_VERSION,
        "estimators": {
            "pit": "randomised PIT indicator (as published)",
            "crps": "sample estimator with self-pairs (as published)",
        },
        "seasons": {},
    }
    lines = [
        "# Past-season reference (Season Review)",
        "",
        "Generated by `ml/experiments/season_reference.py` from the stored walk-forward rows "
        "(horizon 0) with `fpl_forecasting.season_eval`. Used by the Season Review as context "
        "for the live record over the same gameweeks; never pooled with it.",
        "",
        "| season | population | gameweeks | rows | RMSE model | RMSE ppg | CRPS model | "
        "CRPS clim | PIT-80 | CITL P(≥6) | CITL P(start) |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    sds: dict[str, list[float]] = {"citl_6": [], "citl_start": [], "pit80": []}
    for season, s_rows in rows.groupby("season", sort=True):
        out["seasons"][str(season)] = {}
        for pop, mask in (
            ("all", np.ones(len(s_rows), bool)),
            ("regulars", s_rows["regular"].to_numpy(bool)),
        ):
            sums = se.gameweek_sums(se.row_scores(s_rows[mask]))
            out["seasons"][str(season)][pop] = json.loads(sums.to_json(orient="records"))
            w = se.summarize(sums)
            lv = w["levels"]
            lines.append(
                f"| {season} | {pop} | {w['G']} | {w['rows']:,} | {lv['rmse']['model']:.3f} | "
                f"{lv['rmse']['ppg']:.3f} | {lv['crps']['model']:.3f} | "
                f"{lv['crps']['climatology']:.3f} | {lv['pit80']:.3f} | {lv['citl_6']:+.4f} | "
                f"{lv['citl_start']:+.4f} |"
            )
            if pop == "all":
                for k, spec in se.MARGINS.items():
                    sds[spec["statistic"]] += w["calibration"][k]["per_gameweek"]
    lines += [
        "",
        "Per-gameweek mean and SD across the three seasons (population all, horizon 0), the "
        "variability the contract's equivalence margins were set against:",
        "",
        "| statistic | mean | SD | gameweeks |",
        "|---|---|---|---|",
    ]
    for k, v in sds.items():
        a = np.asarray(v)
        lines.append(f"| {k} | {a.mean():+.4f} | {a.std(ddof=1):.4f} | {len(a)} |")
    rep = ROOT / "ml" / "reports"
    (rep / "season_reference.json").write_text(json.dumps(out, separators=(",", ":")) + "\n")
    (rep / "season_reference.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
