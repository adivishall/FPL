"""Feature importance and its stability across training cutoffs (§57.2 'Track feature
importance / attribution and investigate unstable features').

Trains the start-probability classifier, the direct points regressor and the price-rise
classifier at several walk-forward cutoffs and records normalised gain importance. A feature
whose importance share swings strongly between consecutive retrains (coefficient of variation
> 0.5 while in the top 15) is flagged for investigation.

Usage: uv run python ml/experiments/feature_importance.py [snapshot_dir]
Outputs: ml/reports/feature_importance.{json,md}
"""

from __future__ import annotations

import json
import sys
from itertools import pairwise
from pathlib import Path

import numpy as np
import pandas as pd

from fpl_forecasting.direct import DirectPointsModel
from fpl_forecasting.minutes import MinutesModel
from fpl_forecasting.model_config import minutes_spec, price_spec
from fpl_forecasting.pipeline import TRAIN_HORIZONS
from fpl_forecasting.price_change import PriceChangeModel, training_rows
from fpl_forecasting.walkforward import FeatureCache, cutoffs, training_table
from fpl_storage.dataset import load_snapshot
from fpl_storage.pit import PointInTimeView

ROOT = Path(__file__).resolve().parents[2]
CUTS = [
    ("2023-24", 10),
    ("2023-24", 30),
    ("2024-25", 10),
    ("2024-25", 30),
    ("2025-26", 10),
    ("2025-26", 30),
]
SEASONS = ["2022-23", "2023-24", "2024-25", "2025-26"]


def _gain(booster_model) -> pd.Series:  # type: ignore[no-untyped-def]
    b = booster_model.booster_
    imp = pd.Series(b.feature_importance(importance_type="gain"), index=b.feature_name())
    return imp / imp.sum()


def main() -> None:
    snap = (
        Path(sys.argv[1])
        if len(sys.argv) > 1
        else sorted((ROOT / "data" / "snapshots").glob("snap_*"))[-1]
    )
    ds = load_snapshot(snap)
    cache = FeatureCache(ds, 5, ROOT / "data" / "feature-store")
    hist = cutoffs(ds, SEASONS)
    imps: dict[str, dict[str, pd.Series]] = {"start": {}, "direct_points": {}, "price_rise": {}}
    for season, gw in CUTS:
        cut = next(c for c in hist if c.season == season and c.gw == gw)
        key = f"{season} GW{gw}"
        tab = training_table(cache, cut, hist, TRAIN_HORIZONS)
        mm = MinutesModel(minutes_spec()[0].params).fit(tab)
        assert mm.start_clf is not None
        imps["start"][key] = _gain(mm.start_clf)
        dm = DirectPointsModel()
        dm.fit(tab)
        imps["direct_points"][key] = _gain(dm.model)
        view = PointInTimeView(ds, cut.cutoff)
        pr = PriceChangeModel(price_spec()[0].params).fit(
            training_rows(view, [s for s in SEASONS if s <= season])
        )
        imps["price_rise"][key] = _gain(pr.clfs["rise"][0])
        print(key, "done", flush=True)
    out: dict[str, object] = {
        "snapshot_id": ds.snapshot_id,
        "cutoffs": [f"{s} GW{g}" for s, g in CUTS],
    }
    lines = [
        "# Feature importance stability",
        "",
        f"Snapshot `{ds.snapshot_id}`; normalised LightGBM gain at {len(CUTS)} training cutoffs "
        f"({', '.join(out['cutoffs'])}). Generated by `ml/experiments/feature_importance.py`.",
        "",
        "*rank stability* = mean Spearman correlation of importance between consecutive cutoffs; "
        "*unstable* = top-15 feature with coefficient of variation of its share > 0.5.",
        "",
    ]
    for model, d in imps.items():
        df = pd.DataFrame(d).fillna(0.0)
        mean = df.mean(axis=1).sort_values(ascending=False)
        cv = (df.std(axis=1) / df.mean(axis=1).replace(0, np.nan)).reindex(mean.index)
        cols = list(df.columns)
        stab = float(np.mean([df[a].corr(df[b], method="spearman") for a, b in pairwise(cols)]))
        top = mean.head(15)
        unstable = [f for f in top.index if cv[f] > 0.5]
        out[model] = {
            "rank_stability": stab,
            "top15": {f: {"mean_share": float(top[f]), "cv": float(cv[f])} for f in top.index},
            "unstable": unstable,
            "by_cutoff": df.round(5).to_dict(),
        }
        lines += [
            f"## {model}",
            "",
            f"Rank stability {stab:.3f}; unstable features: {', '.join(unstable) or 'none'}.",
            "",
            "| feature | mean gain share | CV across cutoffs |",
            "|---|---|---|",
        ]
        lines += [f"| {f} | {top[f]:.3f} | {cv[f]:.2f} |" for f in top.index]
        lines.append("")
    rep = ROOT / "ml" / "reports"
    (rep / "feature_importance.json").write_text(json.dumps(out, indent=2) + "\n")
    (rep / "feature_importance.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
