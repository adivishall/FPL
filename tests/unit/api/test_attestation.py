"""FPL server time for the forecast record (contract §2.3): only FPL's official API over HTTPS
counts, ``Date`` and ``Age`` give a conservative upper bound on when a request was sent, and a
failure yields no evidence rather than an error or a guess from the host's clock."""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

import httpx
import pytest

from fpl_api.attestation import (
    FplServerClock,
    ServerTime,
    UntrustedTimeSource,
    from_response,
    official,
    read,
)
from fpl_ingestion.http import HttpConfig, HttpFetcher

URL = "https://fantasy.premierleague.com/api/event-status/"
LOCAL = datetime(2026, 10, 14, 6, 46, 48, tzinfo=UTC)


def test_date_and_age_bound_the_request_conservatively() -> None:
    t = from_response(URL, {"date": "Wed, 14 Oct 2026 06:46:47 GMT", "age": "276"}, LOCAL, LOCAL)
    assert t.date == datetime(2026, 10, 14, 6, 46, 47, tzinfo=UTC)
    assert t.not_before == t.date  # generated by then: anything started after receipt is later
    # sent no later than Date + Age, plus Date's whole-second resolution
    assert t.not_after == t.date + timedelta(seconds=277)
    no_age = from_response(URL, {"date": "Wed, 14 Oct 2026 06:46:47 GMT"}, LOCAL, LOCAL)
    assert no_age.not_after == no_age.date + timedelta(seconds=1)
    ev = t.evidence()
    assert ev["host_skew_seconds"] == 1.0 and ev["age_seconds"] == 276 and ev["url"] == URL


@pytest.mark.parametrize(
    "url",
    [
        "http://fantasy.premierleague.com/api/event-status/",
        "https://fantasy.premierleague.com.example.test/api/event-status/",
        "https://example.test/api/event-status/",
    ],
)
def test_only_the_official_api_over_https_counts(url: str) -> None:
    assert not official(url)
    with pytest.raises(UntrustedTimeSource):
        from_response(url, {"date": "Wed, 14 Oct 2026 06:46:47 GMT"}, LOCAL, LOCAL)
    with pytest.raises(UntrustedTimeSource):
        FplServerClock(HttpFetcher(HttpConfig(allowed_hosts=("example.test",))), url[:-14])


@pytest.mark.parametrize(
    "headers",
    [
        {},
        {"date": "not a date"},
        {"date": "Wed, 14 Oct 2026 06:46:47 -0000"},  # no zone
        {"date": "Wed, 14 Oct 2026 06:46:47 GMT", "age": "-5"},
        {"date": "Wed, 14 Oct 2026 06:46:47 GMT", "age": "soon"},
    ],
)
def test_a_missing_or_malformed_header_is_no_evidence(headers: dict[str, str]) -> None:
    with pytest.raises(ValueError, match=r"Date|Age|date"):
        from_response(URL, headers, LOCAL, LOCAL)


def _clock(handler: httpx.MockTransport) -> FplServerClock:
    fetcher = HttpFetcher(
        HttpConfig(allowed_hosts=("fantasy.premierleague.com",), max_retries=1),
        client=httpx.Client(transport=handler),
    )
    return FplServerClock(fetcher, "https://fantasy.premierleague.com/api")


def test_the_clock_reads_fpls_response_headers() -> None:
    seen: list[str] = []

    def handler(request: httpx.Request) -> httpx.Response:
        seen.append(str(request.url))
        return httpx.Response(
            200, json={}, headers={"Date": "Wed, 14 Oct 2026 06:46:47 GMT", "Age": "3"}
        )

    t = _clock(httpx.MockTransport(handler)).now()
    assert seen == [URL]
    assert t.not_after == datetime(2026, 10, 14, 6, 46, 51, tzinfo=UTC)
    assert t.local_sent <= t.local_received


def test_an_unreachable_fpl_gives_no_time_and_never_the_hosts_clock() -> None:
    def down(request: httpx.Request) -> httpx.Response:
        raise httpx.ConnectError("unreachable", request=request)

    assert read(_clock(httpx.MockTransport(down)), "test") is None
    assert read(None, "test") is None

    def no_date(request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, json={})

    # httpx adds no Date of its own: a response without one is no evidence
    assert read(_clock(httpx.MockTransport(no_date)), "test") is None


def test_server_time_is_a_value() -> None:
    t = ServerTime(URL, LOCAL, 0, LOCAL, LOCAL)
    assert t.not_before <= t.not_after and t.served_by is None
